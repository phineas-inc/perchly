// Generates src/data/southAsiaMap.ts from Natural Earth (via world-atlas).
// Run: pnpm build:map
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath, geoGraticule10 } from "d3-geo";
import { feature, mesh } from "topojson-client";

const W = 700;
const H = 430;
const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const countries = feature(topo, topo.objects.countries);
const borders = mesh(topo, topo.objects.countries, (a, b) => a !== b);

// lon/lat window shown on the map
const [west, east, south, north] = [60, 99, 4, 38];
const window = { type: "Polygon", coordinates: [[[west, south], [west, north], [east, north], [east, south], [west, south]]] };
const projection = geoMercator().fitExtent([[0, 0], [W, H]], window);
projection.clipExtent([[0, 0], [W, H]]);
const path = geoPath(projection).digits(1);

const stations = {
  Nashik: [73.79, 19.99],
  Bengaluru: [77.59, 12.97],
  Lucknow: [80.95, 26.85],
  "Port Blair": [92.73, 11.62],
};

// Sun-synchronous LEO ground tracks (i = 97.8°, ~95 min period) as lon/lat polylines.
function groundTrack(lon0, uStart, uEnd) {
  const inc = (97.8 * Math.PI) / 180;
  const pts = [];
  for (let u = uStart; u <= uEnd; u += 0.02) {
    const lat = Math.asin(Math.sin(inc) * Math.sin(u));
    const earthRot = (u / (2 * Math.PI)) * (95 / 1436) * 2 * Math.PI;
    let lon = lon0 + Math.atan2(Math.cos(inc) * Math.sin(u), Math.cos(u)) - earthRot;
    pts.push([(lon * 180) / Math.PI, (lat * 180) / Math.PI]);
  }
  return { type: "LineString", coordinates: pts };
}
const rad = (d) => (d * Math.PI) / 180;
const tracks = [
  groundTrack(rad(70), -0.9, 0.9),
  groundTrack(rad(80), -0.9, 0.9),
  groundTrack(rad(91), -0.9, 0.9),
];

const out = {
  width: W,
  height: H,
  countries: countries.features.map((f) => path(f)).filter(Boolean).join(""),
  india: path(countries.features.find((f) => f.properties.name === "India")) ?? "",
  borders: path(borders) ?? "",
  graticule: path(geoGraticule10()) ?? "",
  tracks: tracks.map((t) => path(t) ?? ""),
  stations: Object.fromEntries(
    Object.entries(stations).map(([name, ll]) => {
      const [x, y] = projection(ll);
      return [name, { x: +x.toFixed(1), y: +y.toFixed(1) }];
    }),
  ),
  // pixels per km at the map centre, for the scale bar
  kmPerPx: (() => {
    const c = projection.invert([W / 2, H / 2]);
    const d = (a, b) => {
      const R = 6371, p1 = rad(a[1]), p2 = rad(b[1]), dl = rad(b[0] - a[0]);
      return R * Math.acos(Math.sin(p1) * Math.sin(p2) + Math.cos(p1) * Math.cos(p2) * Math.cos(dl));
    };
    return +(d(c, projection.invert([W / 2 + 100, H / 2])) / 100).toFixed(3);
  })(),
};

writeFileSync(
  "src/data/southAsiaMap.ts",
  `// Generated by scripts/build-map.mjs from Natural Earth 1:50m (public domain). Do not edit.\nexport const southAsiaMap = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log("wrote src/data/southAsiaMap.ts", out.kmPerPx, "km/px", Object.keys(out.stations));
